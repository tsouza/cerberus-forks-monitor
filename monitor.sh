#!/usr/bin/env bash
#
# cerberus-forks-monitor — daily sync worker.
#
# For each entry in monitor.yml:
#   1. Clone upstream + fork.
#   2. Look at commits in upstream/main since the last cerberus tag on
#      fork_branch. If none of those commits touched relevant_paths,
#      skip silently.
#   3. Otherwise rebase fork_branch onto upstream/main, run the configured
#      test subtrees, and on success push + tag (bumping the patch).
#   4. On any failure — rebase conflict, test red, rejected push, unpublished
#      tag — open an issue in this repo, skip the dep for today, and mark the
#      overall run failed (the remaining deps are still processed).
#
# Dependencies: bash 5+, git, gh, yq, jq, go.

set -euo pipefail

CONFIG="${MONITOR_CONFIG:-monitor.yml}"
WORK_ROOT="$(mktemp -d -t cerberus-forks-monitor-XXXXXX)"
MONITOR_REPO="${MONITOR_REPO:-tsouza/cerberus-forks-monitor}"

# The identity every replayed commit is rewritten to before being pushed.
#
# GitHub refuses (GH007) any push that would publish an address its owner has
# marked private, and the fork branches carry commits authored from personal
# addresses. `git rebase` preserves those authors, so EVERY push this monitor
# ever attempted was declined at the remote — for 51 consecutive days the
# prometheus dep rebased cleanly, passed its tests, and then failed one line
# later. Nothing upstream of the push could detect it, which is why the daily
# run was red without a single issue naming the cause.
#
# Rewriting is the honest record rather than a workaround: the monitor is not
# a person, and a commit it generated by replaying a patch onto a new base is
# its work. The original authorship stays reachable through the pre-rebase tag.
BOT_NAME="${MONITOR_BOT_NAME:-cerberus-forks-monitor}"
BOT_EMAIL="${MONITOR_BOT_EMAIL:-cerberus-forks-monitor@users.noreply.github.com}"

if [[ ! -f "${CONFIG}" ]]; then
  echo "monitor.yml not found at ${CONFIG}" >&2
  exit 1
fi

if ! command -v yq >/dev/null; then
  echo "yq not installed; aborting" >&2
  exit 1
fi

log() {
  printf '[%s] %s\n' "$(date -u +%H:%M:%S)" "$*"
}

# Bump the patch component of a semver-ish tag. Preserves the cerberus
# pre-release suffix.
#  v0.0.1-cerberus-parser  -> v0.0.2-cerberus-parser
#  v3.0.7-cerberus-parser  -> v3.0.8-cerberus-parser
bump_patch() {
  local tag="$1"
  local body="${tag#v}"
  local suffix=""
  if [[ "${body}" == *-* ]]; then
    suffix="-${body#*-}"
    body="${body%%-*}"
  fi
  local major minor patch
  IFS=. read -r major minor patch <<<"${body}"
  patch=$((patch + 1))
  printf 'v%s.%s.%s%s\n' "${major}" "${minor}" "${patch}" "${suffix}"
}

# Map an upstream release tag to the fork tag that carries it, in the Go
# module numbering upstream publishes for the same release (prometheus v3.15.0
# is the Go module v0.315.0), with the cerberus suffix of last_tag:
#  v3.15.0, v0.311.3-cerberus-parser  -> v0.315.0-cerberus-parser
release_tag() {
  local release="$1" last_tag="$2"
  local suffix=""
  if [[ "${last_tag}" == *-* ]]; then
    suffix="-${last_tag#*-}"
  fi
  local major minor patch
  IFS=. read -r major minor patch <<<"${release#v}"
  printf 'v0.%d.%d%s\n' "$((major * 100 + minor))" "${patch}" "${suffix}"
}

# Reads a list-valued dep field into the named array.
#
# `mapfile -t arr < <(yq ...)` discards yq's exit status, so a config typo or
# an expression this yq build rejects yields an EMPTY ARRAY that reads exactly
# like a legitimately absent optional field. That is how
# `.submodule_tag_paths[]? // empty` — `empty` is a jq builtin, not a yq one —
# silently disabled every per-submodule tag: the expression errored on every
# dep, every day, and the loop over the empty array minted nothing. Capturing
# the output first makes the failure abort the dep instead.
#
# An absent optional field is NOT an error: yq exits 0 and prints nothing, so
# it is normalised to an empty array here.
yq_list() {
  local -n __dest="$1"
  local name="$2" field="$3" raw
  if ! raw="$(yq -r ".deps[] | select(.name == \"${name}\") | .${field}[]" "${CONFIG}" 2>&1)"; then
    log "    reading .${field} for ${name} failed: ${raw}"
    return 1
  fi
  if [[ -z "${raw}" ]]; then
    __dest=()
  else
    mapfile -t __dest <<<"${raw}"
  fi
}

# Report a failure as exactly one open issue per (dep, failure kind). Returns
# nonzero (and logs) if the issue call itself fails, so a broken reporting path
# can never quietly stand in for a working one.
#
# Titles deliberately carry no date. This runs daily against a fork nobody
# fixes the same morning, so a dated title made every run mint a NEW issue
# describing the identical unfixed problem: three stuck deps produced 131 open
# issues, which is indistinguishable at a glance from 131 distinct problems and
# buries any real one. Reusing the open issue makes the issue COUNT mean
# "distinct broken things" and the comment thread mean "how long it has been
# broken" — both of which are information; a pile of duplicates is not.
open_issue() {
  local title="$1"
  local body="$2"
  local existing
  existing="$(gh -R "${MONITOR_REPO}" issue list \
    --state open --label "monitor-failure" --limit 100 --json number,title 2>/dev/null |
    jq -r --arg t "${title}" 'map(select(.title == $t)) | first | .number // empty')" || existing=""

  if [[ -n "${existing}" ]]; then
    if ! gh -R "${MONITOR_REPO}" issue comment "${existing}" \
      --body "Still failing as of $(date -u +%Y-%m-%d)."$'\n\n'"${body}" >/dev/null; then
      log "    FAILED to comment on issue #${existing}: ${title}"
      return 1
    fi
    log "    updated existing issue #${existing}"
    return 0
  fi

  if ! gh -R "${MONITOR_REPO}" issue create \
    --title "${title}" \
    --body "${body}" \
    --label "monitor-failure" >/dev/null; then
    log "    FAILED to open issue: ${title}"
    return 1
  fi
}

# Create a tag on HEAD and publish it, reporting git's own words on failure.
#
# A tag that never lands is the quietest failure this script has: the branch
# push already succeeded, so the fork looks synced from every angle, while
# cerberus's go.mod keeps resolving to the previous tag and Dependabot has
# nothing to offer. Nothing downstream can notice, so the issue is the only
# signal that exists.
publish_tag() {
  local name="$1" fork="$2" tag="$3" out
  if ! out="$({ git tag "${tag}" && git push origin "${tag}"; } 2>&1)"; then
    log "    publishing tag ${tag} failed: ${out}"
    open_issue \
      "[${name}] tag ${tag} could not be published" \
      "\`${fork}\` was rebased and force-pushed, but publishing \`${tag}\` failed, so cerberus's go.mod still resolves to the previous tag. Git said:
\`\`\`
${out}
\`\`\`" || true
    return 1
  fi
  log "    published tag ${tag}"
}

process_dep() {
  local name="$1"
  local upstream fork fork_branch tag_prefix
  upstream="$(yq -r ".deps[] | select(.name == \"${name}\") | .upstream" "${CONFIG}")"
  fork="$(yq -r ".deps[] | select(.name == \"${name}\") | .fork" "${CONFIG}")"
  fork_branch="$(yq -r ".deps[] | select(.name == \"${name}\") | .fork_branch" "${CONFIG}")"
  tag_prefix="$(yq -r ".deps[] | select(.name == \"${name}\") | .tag_prefix" "${CONFIG}")"
  local test_workdir
  test_workdir="$(yq -r ".deps[] | select(.name == \"${name}\") | .test_workdir // \"\"" "${CONFIG}")"
  local track
  track="$(yq -r ".deps[] | select(.name == \"${name}\") | .track // \"main\"" "${CONFIG}")"
  if [[ "${track}" != "main" && "${track}" != "release" ]]; then
    log "==> ${name}: .track is \"${track}\"; expected main or release"
    return 1
  fi

  # Every field above is mandatory; yq prints the string `null` for a key that
  # is absent, so an entry missing one would otherwise run against a remote
  # literally named "null".
  local field
  for field in upstream fork fork_branch tag_prefix; do
    if [[ -z "${!field}" || "${!field}" == "null" ]]; then
      log "==> ${name}: config is missing .${field}"
      return 1
    fi
  done

  local relevant_paths test_subtrees submodule_tag_paths
  yq_list relevant_paths "${name}" relevant_paths || return 1
  yq_list test_subtrees "${name}" test_subtrees || return 1
  yq_list submodule_tag_paths "${name}" submodule_tag_paths || return 1

  # Both lists are mandatory, and an empty one is worse than a missing dep:
  # `git log -- ` with no pathspec matches EVERY upstream commit, so the monitor
  # would rebase and tag on every unrelated change — the exact Dependabot noise
  # this repo exists to suppress. An empty test_subtrees skips the test gate
  # entirely and force-pushes an unvalidated rebase. Only submodule_tag_paths is
  # legitimately optional (single-module forks have none).
  if (( ${#relevant_paths[@]} == 0 )); then
    log "==> ${name}: .relevant_paths is empty; refusing to treat every upstream commit as relevant"
    return 1
  fi
  if (( ${#test_subtrees[@]} == 0 )); then
    log "==> ${name}: .test_subtrees is empty; refusing to push an untested rebase"
    return 1
  fi

  log "==> ${name}: upstream=${upstream} fork=${fork} branch=${fork_branch}"

  # NOTE: main() calls this function as an `if` condition, which makes
  # bash ignore `set -e` inside the function body — every command that
  # must abort the dep on failure needs an explicit guard.
  local work="${WORK_ROOT}/${name}"
  if ! git clone --quiet "https://github.com/${fork}.git" "${work}"; then
    log "    clone of ${fork} failed"
    return 1
  fi
  pushd "${work}" >/dev/null

  # Committer identity for everything produced below. The author is rewritten
  # separately during the rebase; GH007 rejects a private address in EITHER
  # field, so both have to be the bot.
  if ! git config user.name "${BOT_NAME}" || ! git config user.email "${BOT_EMAIL}"; then
    log "    setting the bot git identity failed"
    popd >/dev/null
    return 1
  fi

  if ! git remote add upstream "https://github.com/${upstream}.git" ||
     ! git fetch --quiet --tags upstream "+refs/heads/main:refs/remotes/upstream/main" ||
     ! git fetch --quiet --tags origin; then
    log "    fetching ${upstream} / ${fork} failed"
    popd >/dev/null
    return 1
  fi

  # Find the last cerberus tag on fork_branch. Falls back to the branch root
  # commit if no tag exists yet.
  local last_tag
  last_tag="$(git describe --tags --abbrev=0 --match "${tag_prefix}.*-cerberus-*" "origin/${fork_branch}" 2>/dev/null || true)"
  if [[ -z "${last_tag}" ]]; then
    log "    no cerberus tag found on ${fork_branch}; cannot proceed safely"
    open_issue "[${name}] no baseline cerberus tag" "Run an initial tag mint on \`${fork}\` before the monitor can take over." || true
    popd >/dev/null
    return 1
  fi
  log "    last tag: ${last_tag}"

  # The commit the branch is rebased onto. track: main follows upstream/main
  # and moves only when a relevant path changed. track: release follows the
  # newest stable upstream release and moves whenever a newer one exists,
  # because cerberus pins its reference server to the same release.
  local base_ref fetch_spec new_tag=""
  if [[ "${track}" == "release" ]]; then
    local release
    release="$(git tag -l 'v*' --sort=-v:refname | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | head -n 1 || true)"
    if [[ -z "${release}" ]]; then
      log "    no stable release tag found on ${upstream}"
      open_issue "[${name}] no upstream release tag" "The monitor found no \`vX.Y.Z\` tag on \`${upstream}\` to follow." || true
      popd >/dev/null
      return 1
    fi
    new_tag="$(release_tag "${release}" "${last_tag}")"
    if [[ "${new_tag}" == "${last_tag}" ]]; then
      log "    already on ${release} (${last_tag}); skipping"
      popd >/dev/null
      return 0
    fi
    log "    newer release: ${release}"
    base_ref="${release}"
    fetch_spec="tag ${release}"
  else
    base_ref="upstream/main"
    fetch_spec="main"
    # Did anything in relevant_paths change in upstream since last tag?
    local changed
    changed="$(git log --pretty=format:%H "${last_tag}..upstream/main" -- "${relevant_paths[@]}" || true)"
    if [[ -z "${changed}" ]]; then
      log "    no relevant changes since ${last_tag}; skipping"
      popd >/dev/null
      return 0
    fi
    log "    relevant commits: $(echo "${changed}" | wc -l)"
  fi

  if ! git checkout --quiet "${fork_branch}"; then
    log "    checkout of ${fork_branch} failed"
    popd >/dev/null
    return 1
  fi
  # --exec runs after each replayed commit, rewriting its author to the bot so
  # the push below is not rejected as publishing a private address. It cannot
  # touch an upstream commit: the todo list only ever holds the fork's own.
  if ! git rebase "${base_ref}" \
    --exec "git commit --amend --no-edit --author='${BOT_NAME} <${BOT_EMAIL}>'"; then
    log "    rebase conflict; opening issue"
    local conflict
    conflict="$(git status --short || true)"
    git rebase --abort || true
    open_issue \
      "[${name}] rebase conflict" \
      "Rebasing \`${fork_branch}\` onto \`${base_ref}\` produced conflicts. Conflict status:
\`\`\`
${conflict}
\`\`\`

Manual rebase required. After fixing locally and force-pushing, re-run the workflow." || true
    popd >/dev/null
    return 1
  fi

  # Run subtree tests.
  local test_status=0
  if [[ -n "${test_workdir}" ]]; then
    if ! pushd "${test_workdir}" >/dev/null; then
      log "    test_workdir ${test_workdir} does not exist after rebase"
      popd >/dev/null
      return 1
    fi
  fi
  log "    running tests: ${test_subtrees[*]}"
  if ! go test -count=1 "${test_subtrees[@]}"; then
    test_status=1
  fi
  if [[ -n "${test_workdir}" ]]; then
    popd >/dev/null
  fi
  if (( test_status != 0 )); then
    log "    tests red after rebase; opening issue"
    open_issue \
      "[${name}] tests fail after rebase" \
      "Rebasing \`${fork_branch}\` onto \`${base_ref}\` succeeded, but \`go test\` on the cerberus subtree failed. The branch was NOT force-pushed. Reproduce with: \`git clone https://github.com/${fork}.git && cd $(basename "${fork}") && git fetch origin && git checkout ${fork_branch} && git fetch https://github.com/${upstream}.git ${fetch_spec} && git rebase FETCH_HEAD\`." || true
    popd >/dev/null
    return 1
  fi

  # Tests green — push the rebased branch.
  #
  # This is the one step whose failure the run cannot infer from anywhere else.
  # A rejection here (GH007, a lost --force-with-lease race, an expired token)
  # leaves the fork byte-identical to how it started, so tomorrow's run redoes
  # the same rebase and the same tests and fails at the same line, and the only
  # trace is a nonzero exit buried in the job log. That is exactly how the
  # private-address rejection above stayed unnamed for 51 days. Capture the
  # remote's reply and put it in the issue, because the reply IS the diagnosis.
  log "    pushing rebased branch"
  local push_out
  if ! push_out="$(git push --force-with-lease origin "${fork_branch}" 2>&1)"; then
    log "    push of ${fork_branch} failed: ${push_out}"
    open_issue \
      "[${name}] push of ${fork_branch} rejected" \
      "The rebase onto \`${base_ref}\` succeeded and \`go test\` was green, but \`git push --force-with-lease origin ${fork_branch}\` was declined. \`${fork}\` still carries the pre-rebase branch and no tag was minted. The remote said:
\`\`\`
${push_out}
\`\`\`" || true
    popd >/dev/null
    return 1
  fi
  log "    pushed ${fork_branch}: ${push_out}"

  # Mint the new tag: the release's own number on track: release, the next
  # patch on track: main.
  if [[ -z "${new_tag}" ]]; then
    new_tag="$(bump_patch "${last_tag}")"
  fi
  if ! publish_tag "${name}" "${fork}" "${new_tag}"; then
    popd >/dev/null
    return 1
  fi

  # Per-submodule tags (collector-contrib style).
  local sub
  for sub in "${submodule_tag_paths[@]}"; do
    if ! publish_tag "${name}" "${fork}" "${sub}/${new_tag}"; then
      popd >/dev/null
      return 1
    fi
  done

  popd >/dev/null
}

main() {
  local names
  mapfile -t names < <(yq -r '.deps[].name' "${CONFIG}")
  log "monitor run start (deps: ${names[*]})"
  local failures=0
  local failed_deps=()
  for dep in "${names[@]}"; do
    if ! process_dep "${dep}"; then
      failures=$((failures + 1))
      failed_deps+=("${dep}")
    fi
  done
  if (( failures > 0 )); then
    log "monitor run FAILED for ${failures} dep(s): ${failed_deps[*]}"
    exit 1
  fi
  log "monitor run complete"
}

main "$@"
